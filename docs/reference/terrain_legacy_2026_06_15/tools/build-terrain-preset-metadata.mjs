// Builds deterministic TypeScript terrain preset metadata from Rust catalog data.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const checkOnly = process.argv.includes("--check");
const sourcePath = "crates/terrain_core/src/variant.rs";
const outputPath = "src/generated/world/terrainPresets.ts";
const source = readNormalized(sourcePath);
const presets = parsePresetMetadata(source);
const generated = buildTypeScriptModule(presets);
const outputAbsolutePath = resolve(root, outputPath);
const current = existsSync(outputAbsolutePath)
  ? readFileSync(outputAbsolutePath, "utf8")
  : undefined;

if (current !== generated) {
  if (checkOnly) {
    console.error(`Terrain preset metadata output is stale: ${outputPath}`);
    process.exitCode = 1;
  } else {
    mkdirSync(dirname(outputAbsolutePath), { recursive: true });
    writeFileSync(outputAbsolutePath, generated);
    console.log(`Generated ${outputPath}`);
  }
}

function readNormalized(relativePath) {
  return readFileSync(resolve(root, relativePath), "utf8")
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n");
}

function parsePresetMetadata(sourceText) {
  const catalogMatch = sourceText.match(
    /TERRAIN_PRESET_METADATA:\s*\[TerrainPresetMetadata;\s*(\d+)\]\s*=\s*\[([\s\S]*?)\];/
  );
  if (!catalogMatch) {
    throw new Error(`Could not find TERRAIN_PRESET_METADATA in ${sourcePath}.`);
  }

  const expectedCount = Number(catalogMatch[1]);
  const catalogBody = catalogMatch[2];
  const itemPattern =
    /TerrainPresetMetadata\s*\{\s*code:\s*(\d+),\s*id:\s*"([^"]+)",\s*name:\s*"([^"]+)",\s*\}/g;
  const presets = [...catalogBody.matchAll(itemPattern)].map((match) => ({
    code: Number(match[1]),
    id: match[2],
    name: match[3]
  }));

  if (presets.length !== expectedCount) {
    throw new Error(
      `Expected ${expectedCount} terrain presets in ${sourcePath}, found ${presets.length}.`
    );
  }

  const seenCodes = new Set();
  const seenIds = new Set();
  for (const preset of presets) {
    if (!Number.isInteger(preset.code) || preset.code < 0) {
      throw new Error(`Invalid terrain preset code: ${preset.code}`);
    }
    if (seenCodes.has(preset.code)) {
      throw new Error(`Duplicate terrain preset code: ${preset.code}`);
    }
    if (!/^[a-z][A-Za-z0-9]*$/.test(preset.id)) {
      throw new Error(`Invalid terrain preset id: ${preset.id}`);
    }
    if (seenIds.has(preset.id)) {
      throw new Error(`Duplicate terrain preset id: ${preset.id}`);
    }
    seenCodes.add(preset.code);
    seenIds.add(preset.id);
  }

  return presets;
}

function buildTypeScriptModule(presets) {
  return [
    "/* Generated by tools/build-terrain-preset-metadata.mjs. Do not edit by hand. */",
    "",
    `export const TERRAIN_PRESET_DEFINITIONS = ${JSON.stringify(presets, null, 2)} as const;`,
    "",
    "export type TerrainPresetDefinition = typeof TERRAIN_PRESET_DEFINITIONS[number];",
    "",
    "export type TerrainPresetId = TerrainPresetDefinition[\"id\"];",
    "",
    "export const TERRAIN_PRESET_IDS = TERRAIN_PRESET_DEFINITIONS.map(",
    "  (definition) => definition.id",
    ") as readonly TerrainPresetId[];",
    "",
    "export const TERRAIN_PRESET_CODE_BY_ID: Readonly<Record<TerrainPresetId, number>> = Object.freeze(",
    "  Object.fromEntries(",
    "    TERRAIN_PRESET_DEFINITIONS.map((definition) => [definition.id, definition.code])",
    "  ) as Record<TerrainPresetId, number>",
    ");",
    ""
  ].join("\n");
}
