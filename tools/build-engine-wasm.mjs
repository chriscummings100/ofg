import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const checkOnly = process.argv.includes("--check");
const crateName = "engine_core";
const packageName = "engine_core";
const target = "wasm32-unknown-unknown";
const cargoArtifactPath = `target/${target}/release/${crateName}.wasm`;
const assetPath = "assets/wasm/engine_core.wasm";
const generatedPath = "src/generated/engine/engineCoreWasm.ts";
const expectedExports = [
  "memory",
  "ofg_engine_core_version",
  "ofg_engine_create",
  "ofg_engine_create_entity",
  "ofg_engine_create_player",
  "ofg_engine_has_player",
  "ofg_engine_player_camera_entity",
  "ofg_engine_player_mode",
  "ofg_engine_set_player_mode",
  "ofg_engine_toggle_player_mode",
  "ofg_engine_set_player_intent",
  "ofg_engine_set_player_position",
  "ofg_engine_set_player_view",
  "ofg_engine_set_debug_camera",
  "ofg_engine_update_player",
  "ofg_engine_preview_player_x",
  "ofg_engine_preview_player_y",
  "ofg_engine_preview_player_z",
  "ofg_engine_update",
  "ofg_engine_tick",
  "ofg_engine_elapsed_seconds",
  "ofg_engine_entity_count",
  "ofg_engine_player_eye_x",
  "ofg_engine_player_eye_y",
  "ofg_engine_player_eye_z",
  "ofg_engine_player_eye_yaw",
  "ofg_engine_player_eye_pitch",
  "ofg_engine_player_x",
  "ofg_engine_player_y",
  "ofg_engine_player_z",
  "ofg_engine_render_snapshot_f32_count",
  "ofg_engine_render_snapshot_f32_ptr",
  "ofg_engine_write_render_snapshot"
];

const build = spawnSync(
  "cargo",
  ["build", "-p", packageName, "--target", target, "--release"],
  {
    cwd: root,
    stdio: "inherit"
  }
);

if (build.status !== 0) {
  process.exitCode = build.status ?? 1;
  process.exit();
}

const wasmBytes = readFileSync(resolve(root, cargoArtifactPath));
const wasmExports = WebAssembly.Module.exports(new WebAssembly.Module(wasmBytes)).map(
  (entry) => entry.name
);
const missingExports = expectedExports.filter((name) => !wasmExports.includes(name));
if (missingExports.length > 0) {
  console.error(`Engine WASM artifact is missing exports: ${missingExports.join(", ")}`);
  process.exitCode = 1;
  process.exit();
}

const generated = buildTypeScriptModule(wasmBytes);
const assetAbsolutePath = resolve(root, assetPath);
const generatedAbsolutePath = resolve(root, generatedPath);
const currentAsset = existsSync(assetAbsolutePath)
  ? readFileSync(assetAbsolutePath)
  : undefined;
const currentGenerated = existsSync(generatedAbsolutePath)
  ? readFileSync(generatedAbsolutePath, "utf8")
  : undefined;

let hasMismatch = false;

if (!currentAsset || !Buffer.from(currentAsset).equals(Buffer.from(wasmBytes))) {
  if (checkOnly) {
    console.error(`Engine WASM asset is stale: ${assetPath}`);
    hasMismatch = true;
  } else {
    mkdirSync(dirname(assetAbsolutePath), { recursive: true });
    writeFileSync(assetAbsolutePath, wasmBytes);
    console.log(`Generated ${assetPath}`);
  }
}

if (currentGenerated !== generated) {
  if (checkOnly) {
    console.error(`Engine WASM metadata is stale: ${generatedPath}`);
    hasMismatch = true;
  } else {
    mkdirSync(dirname(generatedAbsolutePath), { recursive: true });
    writeFileSync(generatedAbsolutePath, generated);
    console.log(`Generated ${generatedPath}`);
  }
}

if (hasMismatch) {
  process.exitCode = 1;
}

function buildTypeScriptModule(wasmBytes) {
  const artifactHash = createHash("sha256").update(wasmBytes).digest("hex");
  const metadata = {
    id: "engine_core",
    sourceCrate: "crates/engine_core",
    assetPath,
    target,
    artifactHash: `sha256-${artifactHash}`,
    exports: expectedExports
  };

  return [
    "/* Generated by tools/build-engine-wasm.mjs. Do not edit by hand. */",
    "",
    "export type EngineCoreWasmExportName =",
    ...expectedExports.map((name, index) =>
      `  | ${JSON.stringify(name)}${index === expectedExports.length - 1 ? ";" : ""}`
    ),
    "",
    "export type EngineCoreWasmMetadata = {",
    "  readonly id: string;",
    "  readonly sourceCrate: string;",
    "  readonly assetPath: string;",
    "  readonly target: string;",
    "  readonly artifactHash: string;",
    "  readonly exports: readonly EngineCoreWasmExportName[];",
    "};",
    "",
    `export const ENGINE_CORE_WASM_METADATA = Object.freeze(${JSON.stringify(metadata, null, 2)}) as EngineCoreWasmMetadata;`,
    ""
  ].join("\n");
}
